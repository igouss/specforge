use crate::assess::{Assessment, Progress, Row};

const HEADER: &str = "# Requirement trace

Generated by SpecForge from the specifications, the step bindings and the pending table. Do not edit.

| Requirement | Title | Progress | Scenarios | Executable | Pending | Monitored |
|---|---|---|---|---|---|---|
";

fn progress(progress: Progress) -> &'static str {
    match progress {
        Progress::NotStarted => "not started",
        Progress::Partial => "partial",
        Progress::Bound => "bound",
    }
}

fn counted(count: usize, one: &str, many: &str) -> String {
    match count {
        1 => format!("{count} {one}"),
        _ => format!("{count} {many}"),
    }
}

/// When an assessment is drawn, `drawn` shall return the Markdown view SF-005 describes, the same bytes for the same assessment.
pub fn drawn(assessment: &Assessment) -> String {
    let mut view: String = HEADER.to_string();
    for row in &assessment.rows {
        let monitored: &str = if row.monitored { "yes" } else { "no" };
        let title: String = row.title.replace('|', "\\|");
        view.push_str(&format!(
            "| {} | {title} | {} | {} | {} | {} | {monitored} |\n",
            row.requirement,
            progress(row.progress),
            row.scenarios,
            row.executable,
            row.pending
        ));
    }
    let rows: &[Row] = &assessment.rows;
    let with = |wanted: Progress| rows.iter().filter(|row: &&Row| row.progress == wanted).count();
    let sum = |field: fn(&Row) -> usize| rows.iter().map(field).sum::<usize>();
    view.push_str(&format!(
        "\n{}: {} bound, {} partial, {} not started. {}: {} executable, {} pending.\n",
        counted(rows.len(), "requirement", "requirements"),
        with(Progress::Bound),
        with(Progress::Partial),
        with(Progress::NotStarted),
        counted(sum(|row: &Row| row.scenarios), "scenario", "scenarios"),
        sum(|row: &Row| row.executable),
        sum(|row: &Row| row.pending),
    ));
    view
}
